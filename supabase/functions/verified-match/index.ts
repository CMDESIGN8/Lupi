import { calculateSeededTurn, calculateSeededDecision } from "./engine.ts";
import type { UserCard } from "../../../src/types/cards.ts";
import { createClient } from "https://esm.sh/@supabase/supabase-js@2";

const headers = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, apikey, content-type, x-client-info",
  "Access-Control-Allow-Methods": "POST, OPTIONS",
  "Content-Type": "application/json",
};
const reply = (body: unknown, status = 200) =>
  new Response(JSON.stringify(body), { status, headers });

Deno.serve(async (request) => {
  if (request.method === "OPTIONS") return new Response(null, { headers });
  if (request.method !== "POST") return reply({ error: "Method not allowed" }, 405);
  try {
    const auth = request.headers.get("Authorization");
    if (!auth?.startsWith("Bearer ")) return reply({ error: "Unauthorized" }, 401);
    const url = Deno.env.get("SUPABASE_URL");
    const serviceKey = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY");
    if (!url || !serviceKey) return reply({ error: "Server not configured" }, 500);
    const admin = createClient(url, serviceKey, { auth: { persistSession: false } });
    const { data: { user }, error: authError } = await admin.auth.getUser(auth.slice(7));
    if (authError || !user) return reply({ error: "Invalid session" }, 401);
    const body = await request.json();
    if (body.action === "start") {
      if (typeof body.opponent !== "string" ||
          !/^[a-zA-Z0-9 _-]{1,80}$/.test(body.opponent))
        return reply({ error: "Invalid opponent" }, 400);
      // Private seed is cryptographically generated by the trusted edge.
      // Deck and equipped gear are looked up and snapshotted in one DB transaction.
      const seed = crypto.getRandomValues(new Uint32Array(1))[0];
      const { data: sessionId, error: startError } = await admin.rpc(
        "start_verified_match", {
          p_user_id: user.id, p_opponent_key: body.opponent, p_seed: seed,
        },
      );
      if (startError) {
        console.warn("Verified match start rejected:", startError.message);
        return reply({ error: "Cannot start match: check active deck, equipment and unfinished games" }, 409);
      }
      return reply({ session_id: sessionId, state_version: 0 });
    }
    if (body.action === "resume") {
      if (typeof body.session_id !== "string" ||
          !/^[0-9a-f-]{36}$/i.test(body.session_id))
        return reply({ error: "Invalid session" }, 400);
      const { data: session, error } = await admin
        .from("verified_match_sessions")
        .select("id,user_id,opponent_key,turn_index,state_version,user_score,opponent_score,simulation_state,pending_decision,state,expires_at")
        .eq("id", body.session_id).eq("user_id", user.id).single();
      if (error || !session) return reply({ error: "Session not found" }, 404);
      if (session.state === "started" && new Date(session.expires_at).getTime() <= Date.now())
        return reply({ error: "Session expired" }, 410);
      // Never expose simulation_seed, deck_snapshot or service credentials.
      const { user_id: _owner, ...publicSession } = session;
      return reply({ session: publicSession });
    }
    if (body.action === "turn") {
      if (typeof body.session_id !== "string" ||
          !/^[0-9a-f-]{36}$/i.test(body.session_id) ||
          !Number.isSafeInteger(body.expected_version) || body.expected_version < 0)
        return reply({ error: "Invalid turn request" }, 400);
      const { data: session, error } = await admin
        .from("verified_match_sessions")
        .select("id,user_id,state,state_version,turn_index,simulation_seed,deck_snapshot,pending_decision,simulation_state,opponent_key,user_score,opponent_score,expires_at")
        .eq("id", body.session_id).eq("user_id", user.id).single();
      if (error || !session) return reply({ error: "Session not found" }, 404);
      if (session.state !== "started" || new Date(session.expires_at).getTime() <= Date.now())
        return reply({ error: "Session is not active" }, 410);
      if (session.state_version !== body.expected_version)
        return reply({ error: "Stale state version", current_version: session.state_version }, 409);
      if (session.pending_decision)
        return reply({ error: "Resolve pending decision first" }, 409);
      // Never use a deck or seed supplied by the browser.
      // A future transactional start RPC must populate both values.
      if (!Array.isArray(session.deck_snapshot) || session.deck_snapshot.length !== 5 ||
          !Number.isSafeInteger(session.simulation_seed))
        return reply({ error: "Server deck snapshot is not initialized" }, 409);
      const cards = session.deck_snapshot as UserCard[];
      const state = session.simulation_state as Record<string, unknown>;
      const minute = session.turn_index * 5;
      if (session.turn_index >= 8) return reply({ error: "Match turns completed" }, 409);
      const advantage = typeof state.advantage === "number" &&
        Number.isFinite(state.advantage) ? state.advantage : 0;
      const turn = calculateSeededTurn(cards, minute, advantage,
        session.opponent_key, session.simulation_seed, session.turn_index);
      // A single CAS transaction advances the turn. On conflict, the client
      // must resume; never replay a new random turn.
      const { data: nextVersion, error: advanceError } = await admin
        .rpc("advance_verified_match_state", {
          p_session_id: session.id,
          p_expected_version: session.state_version,
          p_turn_index: session.turn_index + 1,
          p_user_score: session.user_score,
          p_opponent_score: session.opponent_score,
          p_simulation_state: { ...state, last_turn: turn },
          p_pending_decision: turn.userPhase.moment ?? null,
        });
      if (advanceError) return reply({ error: "Turn conflict or invalid state" }, 409);
      return reply({ turn, state_version: nextVersion, turn_index: session.turn_index + 1 });
    }
    if (body.action === "decision") {
      if (typeof body.session_id !== "string" ||
          !/^[0-9a-f-]{36}$/i.test(body.session_id) ||
          !Number.isSafeInteger(body.expected_version) || body.expected_version < 0 ||
          typeof body.option_id !== "string" || body.option_id.length > 80)
        return reply({ error: "Invalid decision request" }, 400);
      const { data: session, error } = await admin.from("verified_match_sessions")
        .select("id,user_id,state,state_version,turn_index,simulation_seed,pending_decision,simulation_state,user_score,opponent_score,expires_at")
        .eq("id", body.session_id).eq("user_id", user.id).single();
      if (error || !session) return reply({ error: "Session not found" }, 404);
      if (session.state !== "started" || new Date(session.expires_at).getTime() <= Date.now())
        return reply({ error: "Session is not active" }, 410);
      if (session.state_version !== body.expected_version)
        return reply({ error: "Stale state version", current_version: session.state_version }, 409);
      if (!session.pending_decision || !Number.isSafeInteger(session.simulation_seed))
        return reply({ error: "No valid pending decision" }, 409);
      const context = session.pending_decision;
      let result;
      try {
        result = calculateSeededDecision(context, body.option_id,
          session.simulation_seed, session.turn_index - 1);
      } catch {
        return reply({ error: "Decision is not available" }, 400);
      }
      const userScore = session.user_score + (result.goalFor === "user" ? 1 : 0);
      const opponentScore = session.opponent_score + (result.goalFor === "rival" ? 1 : 0);
      const state = session.simulation_state as Record<string, unknown>;
      const { data: nextVersion, error: advanceError } = await admin
        .rpc("advance_verified_match_state", {
          p_session_id: session.id,
          p_expected_version: session.state_version,
          p_turn_index: session.turn_index,
          p_user_score: userScore,
          p_opponent_score: opponentScore,
          p_simulation_state: { ...state, last_decision: result },
          p_pending_decision: null,
        });
      if (advanceError) return reply({ error: "Decision conflict or invalid state" }, 409);
      return reply({ result, user_score: userScore, opponent_score: opponentScore,
        state_version: nextVersion });
    }
    if (body.action === "finish") {
      if (typeof body.session_id !== "string" ||
          !/^[0-9a-f-]{36}$/i.test(body.session_id))
        return reply({ error: "Invalid session" }, 400);
      const { data: session, error } = await admin.from("verified_match_sessions")
        .select("user_id,created_at,user_score,opponent_score")
        .eq("id", body.session_id).single();
      if (error || !session || session.user_id !== user.id)
        return reply({ error: "Session not found" }, 404);
      // Time alone is NOT proof of a played match. This endpoint remains
      // disabled until a server-authoritative turn/decision transcript exists.
      return reply({ error: "Verified match finalization not enabled yet" }, 501);
    }
    return reply({ error: "Invalid action" }, 400);
  } catch (error) {
    console.error("verified-match:", error);
    return reply({ error: "Could not process match" }, 500);
  }
});
